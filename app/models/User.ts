import { BaseEntity, Column, Entity, Serializable } from '@neogroup/neorm'
import { Locale } from '@/app/i18n/config'
import { getUserDisplayName } from '@/app/utils/users'

/** A GeoQuests player. Signs in with Google or with email + password (verified by email). */
@Entity({ table: 'users' })
export class User extends BaseEntity {
  @Column({ primaryKey: true, autoGenerated: true })
  id!: number

  @Column()
  email!: string

  /** Null for accounts created through Google (they never set a password). */
  @Column()
  passwordHash!: string | null

  /** Player name shown in the game (HUD, summaries). */
  @Column()
  name!: string | null

  /** Last name, shown next to the name. Null: never set (filled from Google on sign-in); '': cleared by the player. */
  @Column()
  lastName!: string | null

  /** Nickname: when set, shown instead of the name and last name. */
  @Column()
  nickname!: string | null

  /** True when the user verified their email address. Always true for Google-authenticated users. */
  @Column({ cast: 'boolean' })
  emailVerified!: boolean

  /** Language chosen by the player (app and emails). */
  @Column()
  locale!: Locale

  /** IANA time zone of the player, sent by its browser: the "day" of its streak and of its daily challenge. Null: UTC. */
  @Column()
  timeZone!: string | null

  /** False disables the account's login. */
  @Column({ cast: 'boolean' })
  active!: boolean

  /** True exempts the player from the ads (set by hand in the database, see app/(protected)/(ads)). */
  @Column({ cast: 'boolean' })
  adsDisabled!: boolean

  @Column({ cast: 'date' })
  createdAt!: Date

  @Serializable()
  get displayName(): string {
    return getUserDisplayName(this)
  }
}
