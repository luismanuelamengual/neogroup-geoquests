import { BaseEntity, Column, Entity } from '@neogroup/neorm'

/** A purchase of the ad-free year (see services/premium.ts). One row per order of the payment provider. */
@Entity({ table: 'payments' })
export class Payment extends BaseEntity {
  @Column({ primaryKey: true, autoGenerated: true })
  id!: number

  @Column({ cast: 'number' })
  userId!: number

  /** Payment provider: 'lemonsqueezy'. */
  @Column()
  provider!: string

  /** Id of the order in the payment provider (unique: a webhook delivered twice is applied once). */
  @Column()
  providerPaymentId!: string

  /** Amount in cents, in `currency`. */
  @Column({ cast: 'number' })
  amount!: number

  /** ISO 4217 code (e.g. 'USD'). */
  @Column()
  currency!: string

  @Column()
  status!: PaymentStatus

  /** Ad-free days the payment granted (taken back on a refund). */
  @Column({ cast: 'number' })
  daysGranted!: number

  @Column({ cast: 'date' })
  createdAt!: Date
}

export type PaymentStatus = 'paid' | 'refunded'
