import { BaseEntity, BelongsTo, Column, Entity } from '@neogroup/neorm'
import { GameRound } from '@/app/(protected)/(game)/models/GameRound'
import { Map } from '@/app/(protected)/(game)/models/Map'

/** The challenge of a day (`daily_challenges`): a classic game with the same rounds for every player. */
@Entity({ table: 'daily_challenges' })
export class DailyChallenge extends BaseEntity {
  @Column({ primaryKey: true, autoGenerated: true })
  id!: number

  /** Day of the challenge (YYYY-MM-DD, in the time zone of the players). */
  @Column()
  day!: string

  @Column({ cast: 'number' })
  mapId!: number

  @Column({ cast: 'json' })
  rounds!: GameRound[]

  @Column({ cast: 'date' })
  createdAt!: Date

  @BelongsTo(() => Map, 'mapId')
  map?: Map
}
