import { BaseEntity, Column, Entity, HasMany } from '@neogroup/neorm'
import { GameMode } from '@/app/(protected)/(game)/models/GameMode'
import { GameRound } from '@/app/(protected)/(game)/models/GameRound'
import { GameStatus } from '@/app/(protected)/(game)/models/GameStatus'

/** A game played by a user: a fixed number of rounds of one mode. */
@Entity({ table: 'games' })
export class Game extends BaseEntity {
  @Column({ primaryKey: true, autoGenerated: true })
  id!: number

  @Column({ cast: 'number' })
  userId!: number

  @Column({ cast: 'number' })
  mode!: GameMode

  @Column({ cast: 'number' })
  status!: GameStatus

  @Column({ cast: 'number' })
  roundsCount!: number

  @Column({ cast: 'number' })
  totalScore!: number

  @Column({ cast: 'date' })
  createdAt!: Date

  @Column({ cast: 'date' })
  finishedAt!: Date | null

  @HasMany(() => GameRound, 'gameId')
  rounds?: GameRound[]
}
